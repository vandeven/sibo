import re

from fpdf import FPDF

from sibo_bot.models import Dish, Restaurant, RestaurantReport

TITLE_BLUE = (24, 76, 120)
SECTION_BLUE = (40, 116, 166)
CARD_FILL = (240, 244, 248)
WAITER_RED = (180, 40, 40)

_CURRENCY = {"€": "EUR ", "£": "GBP ", "¥": "JPY "}


def clean_text(text: str | None) -> str:
    """Makes text safe for the core (latin-1) PDF fonts."""
    if not text:
        return ""
    for symbol, code in _CURRENCY.items():
        text = text.replace(symbol, code)
    return text.encode("latin-1", "replace").decode("latin-1")


def report_filename(report: RestaurantReport) -> str:
    slug = re.sub(r"[^A-Za-z0-9]+", "_", report.location_label).strip("_") or "report"
    return f"SIBO_Guide_{slug}.pdf"


class _GuidePDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 16)
        self.set_text_color(*TITLE_BLUE)
        self.cell(0, 10, "SIBO-Friendly Restaurant Guide", new_x="LMARGIN", new_y="NEXT", align="C")
        self.set_draw_color(200, 200, 200)
        self.line(self.l_margin, 20, self.w - self.r_margin, 20)
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 9)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by SIBO Assistant Bot", align="C")


class ReportRenderer:
    def __init__(self, report: RestaurantReport):
        self.report = report
        self.pdf = _GuidePDF()
        self.pdf.set_auto_page_break(auto=True, margin=15)

    def render(self) -> bytes:
        self.pdf.add_page()
        self._subheader()
        self._section("1. Top 5 best-rated", self.report.top_rated)
        self._section("2. Top 5 cheapest", self.report.cheapest)
        return bytes(self.pdf.output())

    def _line(self, text: str, height: float, *, style: str = "", size: int = 9, color=(40, 40, 40), indent: float = 0):
        self.pdf.set_font("Helvetica", style, size)
        self.pdf.set_text_color(*color)
        self.pdf.set_x(self.pdf.l_margin + indent)
        self.pdf.multi_cell(self.pdf.epw - indent, height, clean_text(text), new_x="LMARGIN", new_y="NEXT")

    def _subheader(self):
        focus = self.report.cuisine or "General menu"
        self._line(f"Area: {self.report.location_label}  |  Focus: {focus}", 8, style="B", size=12, color=(50, 50, 50))
        if self.report.notes:
            self._line(f"Note: {self.report.notes}", 5, style="I", color=(100, 100, 100))
        self.pdf.ln(4)

    def _section(self, title: str, restaurants: list[Restaurant]):
        self._line(title, 10, style="B", size=14, color=SECTION_BLUE)
        self.pdf.ln(2)
        if not restaurants:
            self._line("No restaurants found for this category.", 8, style="I", size=10, color=(100, 100, 100))
            self.pdf.ln(4)
            return
        for rank, restaurant in enumerate(restaurants, 1):
            self._restaurant(rank, restaurant)

    def _restaurant(self, rank: int, restaurant: Restaurant):
        heading = f" {rank}. {restaurant.name}  |  Rating: {restaurant.rating}  |  Price: {restaurant.price_level}"
        self.pdf.set_fill_color(*CARD_FILL)
        self.pdf.set_font("Helvetica", "B", 11)
        self.pdf.set_text_color(20, 20, 20)
        self.pdf.set_x(self.pdf.l_margin)
        self.pdf.multi_cell(self.pdf.epw, 8, clean_text(heading), fill=True, new_x="LMARGIN", new_y="NEXT")

        address = restaurant.address
        if restaurant.distance_km is not None:
            address += f"  ({restaurant.distance_km:.1f} km away)"
        self._line(f"Address: {address}", 6, color=(80, 80, 80), indent=3)
        self.pdf.ln(1)

        for dish in restaurant.dishes:
            self._dish(dish)
        self.pdf.ln(4)

    def _dish(self, dish: Dish):
        self._line(f"- {dish.name} ({dish.price})", 5, style="B", indent=3)
        if dish.why_sibo_friendly:
            self._line(f"Why it's SIBO-friendly: {dish.why_sibo_friendly}", 4.5, color=(70, 70, 70), indent=7)
        if dish.modifications:
            self._line("Ask the waiter:", 4.5, style="BI", color=WAITER_RED, indent=7)
            for change in dish.modifications:
                self._line(f"* {change}", 4.5, style="I", color=WAITER_RED, indent=10)
        else:
            self._line("Safe as served.", 4.5, style="I", color=(60, 120, 60), indent=7)
        self.pdf.ln(1)


def render_report(report: RestaurantReport) -> bytes:
    return ReportRenderer(report).render()
